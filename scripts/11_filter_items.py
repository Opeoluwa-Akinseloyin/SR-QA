"""
11_filter_items.py
------------------
Stage 3.3 of the v2 pipeline: apply the filters to the candidate items one at
a time, logging items / papers / reviews after each, so the paper's funnel
table is generated by script rather than transcribed (a v2 rule: the v1 paper
quoted totals of a different release file than the one it shipped).

Filters, in order (agreed 2026-10-05):

  source      the item links to a CC-BY paper whose full text we hold
              (split into one step per reason it might not, for the funnel)
  answerable  answerability category "reported" and score >= 3 - drops reviewer
              judgements, review-calculated values and bibliographic fields
  non-empty   a blank gold cell is dropped: it could mean "not reported", "not
              applicable" or "not extracted", so it cannot be graded fairly
              (v2.0.1: invisible characters such as a zero-width space count as blank)
  footnote    a gold that is only footnote markers (*, ∗, †, ...) is dropped (v2.0.1)
  dedup       exact duplicates within one review (same paper, question, gold -
              the same study in two of its tables) keep the first

"Not reported"-type gold is KEPT and flagged gold_is_absence: the reviewers
state the paper does not report it, which tests whether a model abstains.
Detection ported from old/scripts/construct_qa.py (is_abstention).

Duplicates ACROSS reviews are kept here: a paper cited by a 2025 and a 2026
review must not land in both splits, which stage 3.4 handles.

Input:   data/v2/items_all.jsonl
Outputs: data/v2/items_filtered.jsonl   the items that pass every filter
         data/v2/funnel.csv             step, items, papers, reviews

Usage:
  python scripts/11_filter_items.py
"""
import csv
import json
import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ITEMS_PATH = os.path.join(BASE, 'data', 'v2', 'items_all.jsonl')
OUT_PATH = os.path.join(BASE, 'data', 'v2', 'items_filtered.jsonl')
FUNNEL_CSV = os.path.join(BASE, 'data', 'v2', 'funnel.csv')

MIN_ANSWERABILITY = 3

# From v1 (construct_qa.py). 'none' or 'nd' stay real answers on purpose.
# v2.0.1 (agreed 2026-10-14): '--', '/' and '\' are placeholders for "not reported / not
# applicable" exactly like the dashes (all 20 of 303 slash golds inspected were).
NR_VALUES = {'', 'nr', 'n/r', 'not reported', 'not stated', 'unclear', 'na', 'n/a',
             'n.a.', 'not specified', 'not applicable', 'not available', '-',
             '—', '–', 'not mentioned', 'not described', '?', '--', '/', '\\'}
NR_PREFIX = ('not reported', 'not stated', 'not applicable', 'not available',
             'not specified', 'not mentioned', 'not described')

# v2.0.1: characters that print as nothing; a gold made only of these is blank (46 golds
# were a lone zero-width space in v2.0)
INVISIBLE = dict.fromkeys(map(ord, '​‌‍⁠﻿ '), ' ')
# v2.0.1: a gold that is only footnote markers is not an answer (106 in v2.0)
FOOTNOTE_MARKS = set('*∗†‡§¶#')


def visible(gold):
    return gold.translate(INVISIBLE).strip()


def is_blank(gold):
    return visible(gold) == ''


def is_footnote_only(gold):
    g = visible(gold).replace(' ', '')
    return bool(g) and set(g) <= FOOTNOTE_MARKS

# Source statuses, removed one at a time in this order (see 10_build_items.py).
SOURCE_STEPS = [
    ('no_ref', 'the map gave the study a citation'),
    ('no_id', 'the citation has a PMCID, PMID or DOI'),
    ('unresolved', 'the identifier was looked up'),
    ('not_in_pmc', 'the paper is in PubMed Central'),
    ('not_downloaded', 'the paper is on disk'),
    ('not_ccby', 'the paper is CC-BY'),
    ('ccby_no_body', 'the file holds the full text'),
]


def is_absence(gold):
    cleaned = ' '.join(visible(gold).lower().split()).strip('.')
    return cleaned in NR_VALUES or cleaned.startswith(NR_PREFIX)


def counts(items):
    return (len(items), len({i['source_pmcid'] for i in items if i['source_pmcid']}),
            len({i['review_pmcid'] for i in items}))


def filter_steps(items):
    """Apply the filters in order; return [(label, items after that step)].

    The first entry is ('candidate items', all items). Shared with
    15_bias_table.py, so the funnel and the bias table use the same steps.
    """
    steps = [('candidate items', items)]

    def step(label, keep):
        steps.append((label, [i for i in steps[-1][1] if keep(i)]))

    for status, label in SOURCE_STEPS:
        step(label, lambda i, s=status: i['source_status'] != s)
    step(f'answerability "reported", score >= {MIN_ANSWERABILITY}',
         lambda i: i['answerability_category'] == 'reported'
         and i['answerability_score'] >= MIN_ANSWERABILITY)
    step('gold cell not blank', lambda i: not is_blank(i['gold']))
    step('gold is not only a footnote marker', lambda i: not is_footnote_only(i['gold']))

    seen = set()

    def first_in_review(item):
        key = (item['review_pmcid'], item['source_pmcid'],
               item['question'].lower(), item['gold'].lower())
        if key in seen:
            return False
        seen.add(key)
        return True
    step('no exact duplicate within a review', first_in_review)
    return steps


def main():
    with open(ITEMS_PATH, encoding='utf-8') as f:
        items = [json.loads(line) for line in f]
    steps = filter_steps(items)
    funnel = [(label, *counts(kept)) for label, kept in steps]
    items = steps[-1][1]

    for item in items:
        item['gold_is_absence'] = is_absence(item['gold'])

    with open(OUT_PATH, 'w', encoding='utf-8') as f:
        for item in items:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')
    with open(FUNNEL_CSV, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['step', 'items', 'papers', 'reviews'])
        writer.writerows(funnel)

    print(f'{"step":<44}{"items":>10}{"papers":>9}{"reviews":>9}')
    for label, n_items, n_papers, n_reviews in funnel:
        print(f'{label:<44}{n_items:>10,}{n_papers:>9,}{n_reviews:>9,}')
    absent = sum(i['gold_is_absence'] for i in items)
    result = sum(i['content'] == 'result' for i in items)
    print(f'\nflagged gold_is_absence: {absent:,} ({absent / len(items):.1%}) | '
          f'result items: {result:,} ({result / len(items):.1%})')
    print(f'-> {OUT_PATH}\n-> {FUNNEL_CSV}')


if __name__ == '__main__':
    main()
